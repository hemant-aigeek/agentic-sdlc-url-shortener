"""Delivery agents: implement, test plan, docs draft, verify (FR-O18, FR-O11, FR-O08).

``ImplementAgent`` writes only inside the run workspace through a ``ChangeSet``
and keeps the receipt needed for a true rollback. ``VerifyAgent`` executes a
real command (the repository's impacted regression targets, or a compile of
the change set) in a subprocess with a timeout; nothing about its result is
narrated — exit code, command and captured output are the evidence.
"""

from __future__ import annotations

import subprocess
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from agentic_sdlc.config import Settings
from agentic_sdlc.errors import StageError, TransientStageError
from agentic_sdlc.orchestration.agents.base import Agent, StageResult
from agentic_sdlc.orchestration.context import RunContext
from agentic_sdlc.orchestration.workspace import ApplyReceipt, ChangeSet, FileChange, Workspace


def _workspace(ctx: RunContext) -> Workspace:
    if not ctx.workspace:
        raise StageError("run has no workspace configured")
    return Workspace(Path(ctx.workspace))


def _slug(text: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in text.lower()).strip("_")[:40]


def _test_module(task: dict[str, Any], criterion: dict[str, str], requirement_version: int) -> str:
    tid = task["id"]
    return f'''"""Generated by the implement stage for {tid} (requirement v{requirement_version}).

Acceptance criterion {criterion["id"]}: {criterion["statement"]}
Observable: {criterion["observable"]}

This is a red test scaffold: it states the expected behaviour as an executable
assertion against the HTTP API and is meant to fail until the implementation
task {task["id"].replace("-test", "-impl")} is done. It is promoted into the
repository only by a human (controlled-autonomy boundary, ADR-010).
"""

import pytest

pytestmark = pytest.mark.req("{criterion["id"]}")


def test_{_slug(criterion["id"])}(client) -> None:  # noqa: ANN001 - fixture from the target repo
    # Arrange: see criterion statement above.
    # Act / Assert: {criterion["observable"]}
    raise AssertionError("not implemented: {criterion["id"]}")
'''


@dataclass
class ImplementAgent(Agent):
    settings: Settings
    name: str = "implement"

    def execute(self, ctx: RunContext, stage: str, attempt: int) -> StageResult:
        normalized = ctx.data.get("normalized")
        decomposition = ctx.output("decompose")
        if not normalized or not decomposition:
            raise StageError("implement requires normalized requirement and decomposition")
        criteria = {c["id"]: c for c in normalized["acceptance_criteria"]}
        tasks: list[dict[str, Any]] = ctx.data.get("decomposition_tasks") or []
        if not tasks:
            # decomposition tasks live in the artifact; rebuild the minimal view from criteria
            tasks = [
                {"id": f"T{i:02d}-test", "kind": "test", "criterion": cid}
                for i, cid in enumerate(criteria, start=1)
            ]
        version = int(normalized.get("version", ctx.requirement_version))
        changes: list[FileChange] = []
        for task in tasks:
            if task.get("kind") != "test":
                continue
            crit = criteria.get(task["criterion"])
            if not crit:
                continue
            changes.append(
                FileChange(
                    path=f"tests/test_{_slug(crit['id'])}.py",
                    content=_test_module(task, crit, version),
                )
            )
        plan_lines = [
            f"# Change set for requirement v{version}: {normalized['title']}",
            "",
            "Generated by the deterministic implement agent. Each red test below states one",
            "acceptance criterion; the implementation tasks are listed with their target",
            "components. Promotion into the repository is a human act.",
            "",
            "| Task | Criterion | Components |",
            "|---|---|---|",
        ]
        for task in ctx.data.get("decomposition_tasks", []):
            plan_lines.append(
                f"| {task['id']} | {task.get('criterion', '-')} | "
                f"{', '.join(task.get('components', [])) or '-'} |"
            )
        changes.append(FileChange(path="CHANGESET.md", content="\n".join(plan_lines) + "\n"))
        change_set = ChangeSet(
            id=f"cs-{ctx.run_id[:8]}-v{version}",
            description=f"red tests + change plan for requirement v{version}",
            changes=changes,
        )
        ws = _workspace(ctx)
        receipt = ws.apply(change_set)
        files = {c.path: c.content or "" for c in changes}
        artifact = {
            **change_set.to_dict(),
            "files": files,
            "workspace": str(ws.root),
            "receipt": receipt.to_dict(),
        }
        return StageResult(
            output={
                "change_set": change_set.id,
                "files_changed": receipt.files_changed,
                "workspace": str(ws.root),
                "reversible": True,
            },
            artifacts=[("change_set", artifact)],
            data_updates={
                "implement_receipt": {
                    "change_set": receipt.change_set,
                    "files_changed": receipt.files_changed,
                    "inverse": receipt.inverse,
                }
            },
        )

    def compensate(self, ctx: RunContext, stage: str) -> dict[str, Any]:
        raw = ctx.data.get("implement_receipt")
        if not raw:
            return {"compensated": False, "rollback": False, "reason": "no change set applied"}
        receipt = ApplyReceipt(
            change_set=raw["change_set"],
            files_changed=list(raw["files_changed"]),
            inverse=dict(raw["inverse"]),
        )
        result = _workspace(ctx).revert(receipt)
        return {"compensated": True, **result}


@dataclass
class TestPlanAgent(Agent):
    __test__ = False  # not a pytest test class

    settings: Settings
    name: str = "test_plan"

    def execute(self, ctx: RunContext, stage: str, attempt: int) -> StageResult:
        normalized = ctx.data.get("normalized")
        if not normalized:
            raise StageError("test_plan requires the normalized requirement")
        cases: list[dict[str, Any]] = []
        for c in normalized["acceptance_criteria"]:
            lower = c["statement"].lower()
            level = (
                "contract"
                if any(k in lower for k in ("endpoint", "return", "status", "/"))
                else "unit"
            )
            cases.append(
                {
                    "id": f"TC-{c['id']}-pos",
                    "criterion": c["id"],
                    "level": level,
                    "negative": False,
                    "given": "a valid precondition for the criterion",
                    "then": c["observable"],
                }
            )
            cases.append(
                {
                    "id": f"TC-{c['id']}-neg",
                    "criterion": c["id"],
                    "level": level,
                    "negative": True,
                    "given": "the precondition is violated (unknown code, expired link, bad input)",
                    "then": "structured problem response with the stated status; no partial effect",
                }
            )
        cases.append(
            {
                "id": "TC-REG",
                "criterion": "ALL",
                "level": "regression",
                "negative": False,
                "given": "the full existing suite",
                "then": "all existing tests remain green (executed by verify)",
            }
        )
        plan = {
            "requirement_version": normalized.get("version", ctx.requirement_version),
            "levels": sorted({c["level"] for c in cases}),
            "cases": cases,
            "tdd": "each positive case is written red before its implementation task",
        }
        return StageResult(
            output={"cases": len(cases), "levels": plan["levels"]},
            artifacts=[("test_plan", plan)],
        )


@dataclass
class DocsDraftAgent(Agent):
    settings: Settings
    name: str = "docs_draft"

    def execute(self, ctx: RunContext, stage: str, attempt: int) -> StageResult:
        normalized = ctx.data.get("normalized")
        if not normalized:
            raise StageError("docs_draft requires the normalized requirement")
        design = ctx.output("design")
        lines = [
            f"# {normalized['title']}",
            "",
            f"Requirement version {normalized.get('version', ctx.requirement_version)} "
            f"({normalized.get('scope', ctx.scope)}).",
            "",
            "## Behaviour",
            *[f"- {s}" for s in normalized["functional_statements"]],
            "",
            "## Acceptance criteria",
            *[
                f"- {c['id']}: {c['statement']} — observable: {c['observable']}"
                for c in normalized["acceptance_criteria"]
            ],
            "",
            "## API impact",
            f"- api_or_schema_impact: {design.get('api_or_schema_impact', False)}",
            f"- contract version impact: {design.get('contract_version_impact', 'n/a')}",
        ]
        if normalized.get("resolved_ambiguities"):
            lines += ["", "## Clarifications applied"]
            lines += [
                f"- {r['ambiguity']}: {r['answer']}" for r in normalized["resolved_ambiguities"]
            ]
        text = "\n".join(lines) + "\n"
        return StageResult(
            output={"sections": 4, "chars": len(text)},
            artifacts=[("docs", {"text": text, "format": "markdown"})],
        )


@dataclass
class VerifyAgent(Agent):
    settings: Settings
    name: str = "verify"

    def execute(self, ctx: RunContext, stage: str, attempt: int) -> StageResult:
        faults = self.settings.demo_fault_verify_transient_failures
        if attempt <= faults:
            raise TransientStageError(
                f"injected transient fault (demo) on attempt {attempt} of {faults}"
            )
        receipt = ctx.data.get("implement_receipt") or {}
        mode = self.settings.verify_mode
        root = self.settings.repository_root.resolve()
        if mode == "compile":
            files = [
                str(Path(ctx.workspace or ".") / p)
                for p in receipt.get("files_changed", [])
                if p.endswith(".py")
            ]
            command = (
                [sys.executable, "-m", "py_compile", *files]
                if files
                else [
                    sys.executable,
                    "-c",
                    "print('nothing to compile')",
                ]
            )
            targets = files
        else:
            targets = [
                t for t in ctx.data.get("impact", {}).get("tests", []) if (root / t).exists()
            ]
            if not targets:
                targets = ["tests/unit", "tests/contract"]
            command = [
                sys.executable,
                "-m",
                "pytest",
                "-q",
                "-p",
                "no:cacheprovider",
                "-x",
                *targets,
            ]
        started = time.monotonic()
        try:
            proc = subprocess.run(
                command,
                cwd=root,
                capture_output=True,
                text=True,
                timeout=self.settings.verify_timeout_s,
                check=False,
            )
        except subprocess.TimeoutExpired as exc:
            raise TransientStageError(
                f"verify command exceeded {self.settings.verify_timeout_s}s"
            ) from exc
        duration = round(time.monotonic() - started, 3)
        tail = (proc.stdout or proc.stderr).strip().splitlines()[-5:]
        output = {
            "executed": True,
            "mode": mode,
            "command": " ".join(command),
            "cwd": str(root),
            "targets": targets,
            "exit_code": proc.returncode,
            "duration_s": duration,
            "output_tail": tail,
            "fault_injected_attempts": faults,
            "attempt": attempt,
        }
        if proc.returncode != 0:
            raise StageError(f"verify failed with exit code {proc.returncode}: {' | '.join(tail)}")
        return StageResult(output=output, artifacts=[("verification", output)])
