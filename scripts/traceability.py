"""Generate docs/traceability.md from the specification, tasks and test markers (SC-03, NFR-09).

Sources (all already in the repository, nothing is hand-maintained twice):

- requirement identifiers and titles: ``specs/.../spec.md`` tables
- tasks and the requirement/ADR ids they cite: ``specs/.../tasks.md``
- tests and the ids they cover: ``@pytest.mark.req(...)`` markers (per test or
  module-level ``pytestmark``)
- executed evidence: ``docs/evidence/<scenario>/run.json``

``--check`` exits non-zero when a functional/non-functional requirement or a
scenario has no covering test, or a test cites an id that does not exist.
"""

from __future__ import annotations

import ast
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "specs" / "001-agentic-url-shortener" / "spec.md"
TASKS = ROOT / "specs" / "001-agentic-url-shortener" / "tasks.md"
TESTS = ROOT / "tests"
EVIDENCE = ROOT / "docs" / "evidence"
OUT = ROOT / "docs" / "traceability.md"

ID_RE = re.compile(r"\b(FR-[UOG]\d{2}|NFR-\d{2}|SCN-[ABC]|SC-\d{2}|AS-\d{2}|AMB-\d{2}|ADR-\d{3})\b")
SCENARIO_EVIDENCE = {"SCN-A": "greenfield", "SCN-B": "brownfield", "SCN-C": "ambiguous"}
# ids that are governance/trace targets rather than testable requirements
NON_TESTABLE_PREFIXES = ("AS-", "AMB-", "ADR-", "SC-")
# requirements verified by a recorded procedure rather than an automated test
MANUAL_EVIDENCE = {"NFR-12": "docs/evidence/clean-clone.md"}


def requirements() -> dict[str, str]:
    out: dict[str, str] = {}
    for line in SPEC.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 2:
            continue
        m = re.fullmatch(r"(FR-[UOG]\d{2}|NFR-\d{2}|SC-\d{2})", cells[0])
        if m:
            title = cells[2] if cells[0].startswith("NFR") and len(cells) > 2 else cells[1]
            out[m.group(1)] = title[:110]
    for sid, title in (
        ("SCN-A", "Greenfield (well-defined requirement)"),
        ("SCN-B", "Brownfield (change to existing behaviour)"),
        ("SCN-C", "Ambiguous requirement"),
    ):
        out[sid] = title
    return out


def tasks() -> dict[str, list[str]]:
    by_req: dict[str, list[str]] = defaultdict(list)
    for line in TASKS.read_text(encoding="utf-8").splitlines():
        m = re.match(r"\|\s*(T-\d{3}|TB-\d{2})\s*\|", line)
        if not m:
            continue
        for rid in set(ID_RE.findall(line)):
            by_req[rid].append(m.group(1))
    return by_req


def _marker_ids(node: ast.AST) -> list[str]:
    ids: list[str] = []
    for sub in ast.walk(node):
        if (
            isinstance(sub, ast.Call)
            and isinstance(sub.func, ast.Attribute)
            and sub.func.attr == "req"
        ):
            ids += [
                a.value
                for a in sub.args
                if isinstance(a, ast.Constant) and isinstance(a.value, str)
            ]
    return ids


def tests() -> dict[str, list[str]]:
    by_req: dict[str, list[str]] = defaultdict(list)
    for path in sorted(TESTS.rglob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        module_ids: list[str] = []
        for node in tree.body:
            if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "pytestmark" for t in node.targets
            ):
                module_ids += _marker_ids(node.value)
        rel = path.relative_to(ROOT).as_posix()
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                ids = module_ids + [i for d in node.decorator_list for i in _marker_ids(d)]
                for rid in sorted(set(ids)):
                    by_req[rid].append(f"{rel}::{node.name}")
    return by_req


def evidence() -> dict[str, str]:
    out: dict[str, str] = {}
    for sid, name in SCENARIO_EVIDENCE.items():
        run = EVIDENCE / name / "run.json"
        if run.exists():
            data = json.loads(run.read_text(encoding="utf-8"))
            out[sid] = f"[docs/evidence/{name}](evidence/{name}/README.md) — {data['state']}"
    return out


def build() -> tuple[str, list[str]]:
    reqs, by_task, by_test, ev = requirements(), tasks(), tests(), evidence()
    problems: list[str] = []
    known = (
        set(reqs)
        | {f"ADR-{i:03d}" for i in range(1, 12)}
        | {f"AS-{i:02d}" for i in range(1, 6)}
        | {f"AMB-{i:02d}" for i in range(1, 13)}
    )
    for rid in by_test:
        if rid not in known:
            problems.append(f"test cites unknown id {rid}: {by_test[rid][0]}")
    lines = [
        "# Traceability Matrix",
        "",
        "Generated by `python scripts/traceability.py` from `spec.md`, `tasks.md`,",
        "`@pytest.mark.req` markers and `docs/evidence/`. Do not edit by hand.",
        "",
        "Chain: Requirement → Scenario → Design (plan §) → ADR → Task → Code → Test →",
        "Validation → Documentation → Evidence.",
        "Design sections and ADRs are cited on each task row in `tasks.md`; code paths are the",
        "task targets; validation is `./scripts/check.sh`; documentation is `docs/`.",
        "",
        "| Requirement | Title | Tasks | Tests | Evidence |",
        "|---|---|---|---|---|",
    ]
    counts = {"covered": 0, "uncovered": 0}
    for rid, title in reqs.items():
        t = by_test.get(rid, [])
        tk = by_task.get(rid, [])
        testable = not rid.startswith(NON_TESTABLE_PREFIXES)
        manual = MANUAL_EVIDENCE.get(rid)
        if manual and (ROOT / manual).exists():
            t = t or [manual]
        if testable and not t:
            problems.append(f"no test covers {rid} ({title})")
            counts["uncovered"] += 1
        elif testable:
            counts["covered"] += 1
        tests_cell = "<br>".join(f"`{x}`" for x in t) if t else "—"
        tasks_cell = ", ".join(tk) if tk else "—"
        ev_cell = ev.get(rid, "`scripts/check.sh`" if t else "—")
        lines.append(f"| {rid} | {title} | {tasks_cell} | {tests_cell} | {ev_cell} |")
    lines += [
        "",
        "## Coverage",
        "",
        f"- Testable requirement ids: {counts['covered'] + counts['uncovered']}; "
        f"covered by at least one test: {counts['covered']}; uncovered: {counts['uncovered']}",
        f"- Requirement marker links: {sum(len(v) for v in by_test.values())} across "
        f"{len({x for v in by_test.values() for x in v})} tests",
        "",
        "## ADR coverage",
        "",
        "| ADR | Tasks | Tests |",
        "|---|---|---|",
    ]
    for i in range(1, 12):
        aid = f"ADR-{i:03d}"
        lines.append(
            f"| {aid} | {', '.join(by_task.get(aid, [])) or '—'} | "
            f"{'<br>'.join(f'`{x}`' for x in by_test.get(aid, [])) or '—'} |"
        )
    lines += ["", "## Orphans", ""]
    lines += [f"- {p}" for p in problems] or ["- none"]
    return "\n".join(lines) + "\n", problems


def main() -> int:
    text, problems = build()
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}; {len(problems)} orphan finding(s)")
    for p in problems:
        print(" -", p)
    return 1 if ("--check" in sys.argv and problems) else 0


if __name__ == "__main__":
    sys.exit(main())
